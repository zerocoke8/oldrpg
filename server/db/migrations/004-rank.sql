-- v4 — 길드 등급. players 에 칼럼 하나를 더한다.
--
-- ★ 왜 표가 아니라 칼럼인가: 등급은 플레이어당 스칼라 하나다. 갱신이
--   UPDATE 한 문장으로 원자적이고, 읽기는 players 를 읽을 때 함께 온다.
--   player_items 가 표여야 했던 이유(수량 갱신의 경합, "누가 무엇을 몇 개"
--   질의)가 여기에는 하나도 없다. 등급이 '이력' 을 갖게 되는 날 —
--   언제 무엇으로 올랐는지를 남기고 싶어지는 날 — 그때 표가 생기고
--   이 칼럼은 그 표의 최신값 캐시가 된다.
--
-- ★ DEFAULT 0 = 미등록. 기존 캐릭터는 전부 미등록으로 들어온다.
--   ALTER TABLE ... ADD COLUMN 은 기존 행을 다시 쓰지 않으므로 값이 나간
--   room_text 도 npc_lines 도 건드려지지 않는다.
--
-- ★ CHECK 를 걸지 않는다. 등급의 상한은 content/balance/ranks.json 이
--   소유하고, 그건 사람이 고치는 데이터다. DDL 에 숫자를 박으면 사다리를
--   한 칸 늘릴 때 마이그레이션이 필요해진다 — 수치를 데이터로 뺀 이유가
--   그것이었다. 음수만 막는다.
-- ---------------------------------------------------------------------------
ALTER TABLE players ADD COLUMN rank INTEGER NOT NULL DEFAULT 0 CHECK (rank >= 0);
